-- Проводки, подходящие к рамке.
--
-- Рамка — это то, что покупатель выбирает первым, и она уже говорит нам
-- и модель, и годы, и панель. Значит проводки логично вешать прямо на
-- неё: промежуточные строки годов (vehicle_wiring) для этого не нужны.
--
-- Храним список артикулов проводок прямо в товаре-рамке. Отдельная
-- таблица связей тут ничего не даёт: список короткий (обычно 1-3
-- позиции), читается всегда целиком вместе с рамкой и правится тоже
-- целиком — как fits, который уже живёт по соседству.
ALTER TABLE products
    ADD COLUMN IF NOT EXISTS frame_wires jsonb NOT NULL DEFAULT '[]'::jsonb;

COMMENT ON COLUMN products.frame_wires IS
    'Артикулы (slug) проводок, подходящих к этой рамке. Пусто — не размечено';

-- Ищем рамки, у которых проводки ещё не проставлены: это главный
-- рабочий фильтр в админке, и он же считает прогресс разметки.
CREATE INDEX IF NOT EXISTS products_frame_wires_idx
    ON products USING gin (frame_wires);
