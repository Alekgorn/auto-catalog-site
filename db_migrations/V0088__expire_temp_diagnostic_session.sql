-- Гасим временную диагностическую сессию: доступ был нужен ровно на то,
-- чтобы выяснить, почему ревизия хранилища показывала ноль файлов.
-- Просроченная сессия недействительна и будет вычищена штатной уборкой
-- при следующем входе в админку.
UPDATE admin_sessions
SET expires_at = NOW() - INTERVAL '1 day'
WHERE token = 'diagnostic-storage-scan-temp-token-2026';
