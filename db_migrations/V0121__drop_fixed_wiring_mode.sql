-- Отключаем режим «Жёстко» в настройках марок.
--
-- Он назначал проводку в обход ручной привязки к рамке и уже дал сбой:
-- у «Газель Бизнес» строка «Жёстко» с ISO-переходником соседствовала с
-- обычной строкой того же периода. Какая победит — вопрос сортировки, а
-- не смысла. Ручная привязка к рамке делает то же самое честнее.
--
-- Строки не удаляем, а переводим в обычный режим: у Civic 2006–2011 в
-- этой же строке записаны кузов «хэтчбек» и левый руль — единственные
-- для поколения. Снести её значило бы перестать спрашивать про кузов
-- там, где разъёмы реально разные.
UPDATE vehicle_wiring
SET mode = 'select',
    wire_slug = ''
WHERE mode = 'fixed';
