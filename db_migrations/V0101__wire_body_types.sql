-- Кузов как условие подбора проводки.
--
-- У машин кузова уже размечены (brands.model_bodies), а у товара такого
-- условия не было. При этом дорогой интерфейс для Civic подходит только
-- на хэтчбек — на седане он физически не встанет, разъёмы другие.
-- Это хуже потери климата: там магнитола хотя бы работает.
--
-- Пустой массив = «любой кузов», поэтому существующие 445 проводок
-- переразмечать не нужно — они продолжат подходить всем.
ALTER TABLE t_p61203256_auto_catalog_site.products
  ADD COLUMN IF NOT EXISTS wire_bodies JSONB NOT NULL DEFAULT '[]'::jsonb;

COMMENT ON COLUMN t_p61203256_auto_catalog_site.products.wire_bodies IS
  'Кузова, на которые встаёт проводка: ["sedan","hatchback"]. Пусто — любой';