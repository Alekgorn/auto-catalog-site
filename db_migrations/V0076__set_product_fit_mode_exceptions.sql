-- Исключения: товар не такой, как вся его категория.
-- Пустой fit_mode у остальных = «взять умолчание категории».

-- Универсальные железки, лежащие в категории подбора по машине
UPDATE products SET fit_mode = 'universal'
WHERE fits = '{}'::jsonb
  AND category IN (
    'Переходники для подключения магнитол',
    'Переходные рамки для магнитол',
    'Штатные разъемы'
  );

-- Товары в универсальных категориях, у которых реально заполнены марки,
-- — значит их всё-таки подбирают по машине
UPDATE products SET fit_mode = 'vehicle'
WHERE fits <> '{}'::jsonb
  AND jsonb_typeof(fits) = 'object'
  AND (SELECT count(*) FROM jsonb_object_keys(fits)) BETWEEN 1 AND 20
  AND category NOT IN (
    'Переходные рамки для магнитол',
    'Переходники для подключения магнитол',
    'Штатные разъемы',
    'Переходные рамки',
    'Переходные жгуты ISO',
    'Под марку'
  );