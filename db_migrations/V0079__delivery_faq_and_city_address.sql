-- Адрес: юридический меняем на город.
-- Самовывоза со склада нет, а конкретный адрес в контактах создавал
-- ложное ожидание, что туда можно приехать за заказом.
UPDATE settings
SET value = jsonb_set(value, '{address}', '"Санкт-Петербург"')
WHERE key = 'contacts';

