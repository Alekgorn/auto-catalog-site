-- Подсказка покупателю на шаге подключения.
--
-- К одной рамке бывает четыре проводки, и различаются они не галочками,
-- а тем, что стояло с завода: монитор, комплектация XP, версия панели.
-- Формально признаки у них совпадают, поэтому подбор вопроса не задаёт —
-- и человек остаётся один на один с четырьмя одинаковыми названиями.
--
-- Текст пишет продавец: он знает, на какой разъём смотреть и чем XP
-- отличается от обычной. Одно предложение здесь стоит дороже любой
-- автоматики.
ALTER TABLE products
    ADD COLUMN IF NOT EXISTS wire_hint text NOT NULL DEFAULT '';

COMMENT ON COLUMN products.wire_hint IS
    'Подсказка к выбору проводки — показывается на шаге подключения';
