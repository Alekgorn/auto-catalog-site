-- Рамка, в которой проводка уже лежит в коробке.
--
-- Часть рамок продаётся комплектом: «Газель Бизнес 10-22 для 12,3 дюйма
-- (авто с климатом) с RGB дефлекторами» — там и рамка, и проводка. Такому
-- покупателю предлагать проводку отдельно нельзя: он купит вторую и
-- вернётся с претензией.
--
-- Отдельный флаг, а не пустой список frame_wires: пустой список означает
-- «ещё не размечено», и отличить его от «проводка не нужна» иначе никак.
ALTER TABLE products
    ADD COLUMN IF NOT EXISTS wire_included boolean NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN products.wire_included IS
    'Проводка входит в комплект рамки — отдельно предлагать не надо';
