/**
 * Короткая контрольная сумма строки.
 *
 * Нужна, чтобы сравнивать состояние товара в каталоге с тем, что попало
 * в собранные для поисковиков страницы. Раньше для этого хранились сами
 * склеенные описания товаров — почти два мегабайта текста в файле
 * состояния, и он переписывался целиком от правки одной цены.
 * Сумма занимает 11 символов вместо килобайта и меняется при любой
 * правке исходной строки.
 *
 * Это не защитная криптография, а быстрый способ заметить изменение —
 * здесь этого достаточно. Важно одно: точно такой же расчёт живёт в
 * scripts/prerender.mjs, и меняться они должны только вместе, иначе
 * админка начнёт считать актуальные страницы устаревшими.
 */
export const pageHash = (input: string): string => {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < input.length; i += 1) {
    const ch = input.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(36);
};

export default pageHash;
