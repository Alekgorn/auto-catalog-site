/**
 * Самый низкий порог из всех способов — с него начинается бесплатная
 * доставка хоть куда-то. По нему считаем подсказку в корзине.
 */
export const FREE_FROM = Math.min(...DELIVERY.map((d) => d.free));

/** Самый высокий порог — бесплатно любым способом */
export const FREE_ALL_FROM = Math.max(...DELIVERY.map((d) => d.free));

/** Минимальная цена доставки — её и называем, чтобы не обещать лишнего */
export const DELIVERY_FROM = Math.min(...DELIVERY.map((d) => d.from));

/**
 * Сколько не хватает до бесплатной доставки. 0 — уже бесплатно.
 * Показываем в корзине: «добавьте на 900 ₽» поднимает средний чек
 * лучше скидки, потому что доставка ощущается пустой тратой.
 */
export const untilFree = (total: number): number =>
  total >= FREE_FROM ? 0 : FREE_FROM - total;