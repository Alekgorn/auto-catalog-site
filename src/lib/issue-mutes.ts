import { adminFetch } from '@/lib/api';

/**
 * Пропущенные находки в проверке данных.
 *
 * Проверки берут на себя лишнее: часть замечаний — не ошибки, а
 * особенность конкретного товара. Универсальная проводка без марок,
 * рамка без совместимости, снятая с продажи позиция без фото. Пока
 * такие висят в списке, каждый обход приходится заново вспоминать,
 * что вот это уже разбирали и оно в порядке.
 *
 * Пропуск скрывает находку из основного списка и кладёт её в
 * отдельный фильтр «Пропущенные» — не удаляет. Вернуть можно в любой
 * момент, ничего безвозвратно не теряется.
 *
 * Храним в общих настройках, а не в браузере: правки нужны и с
 * другого компьютера, и после чистки истории.
 */

/** Ключ настройки, под которым лежит список */
const KEY = 'issueMutes';

export interface IssueMute {
  /** Отпечаток находки — по нему узнаём её при следующем обходе */
  id: string;
  /** Когда пропустили — чтобы видеть давние решения */
  at: number;
  /** Зачем пропустили: «универсальная, подходит ко всем» */
  note?: string;
}

/**
 * Отпечаток находки.
 *
 * Правило плюс предмет, а не порядковый номер: список пересобирается
 * при каждом заходе, и позиция строки в нём непостоянна. Текст
 * замечания в отпечаток не берём — он может содержать цифры (число
 * марок, размер), и от правки товара пропуск бы слетел.
 */
export const muteId = (rule: string, subject: string): string =>
  `${rule}::${subject}`;

/** Загрузить пропущенные. Ошибка сети — пустой список, проверки работают дальше */
export const loadMutes = async (): Promise<IssueMute[]> => {
  try {
    const res = await adminFetch('?action=settings');
    if (!res.ok) return [];
    const data = await res.json();
    const raw = data?.settings?.[KEY];
    return Array.isArray(raw) ? (raw as IssueMute[]) : [];
  } catch {
    return [];
  }
};

/** Сохранить список целиком */
export const saveMutes = async (list: IssueMute[]): Promise<boolean> => {
  try {
    const res = await adminFetch('?action=settings', {
      method: 'PUT',
      body: JSON.stringify({ settings: { [KEY]: list } }),
    });
    return res.ok;
  } catch {
    return false;
  }
};
