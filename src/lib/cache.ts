/**
 * Сброс сохранённых браузером данных сайта.
 *
 * Каталог и настройки лежат в sessionStorage до 10 минут, чтобы не качать
 * их заново на каждом переходе. После правок в админке это значит, что
 * посетитель какое-то время видит старую версию. Сброс убирает копию,
 * и следующая загрузка идёт прямо с сервера.
 */

/** Что храним про сам сайт — это можно чистить смело */
const SITE_KEYS = ['catalog-cache', 'shtatno.filters', 'shtatno.vehicle'];

/**
 * Личное покупателя: корзина, собранный комплект, вход дилера.
 * Не трогаем — человек не должен терять заказ из-за обновления каталога.
 */
export const clearSiteCache = () => {
  if (typeof window === 'undefined') return;

  SITE_KEYS.forEach((key) => {
    try {
      sessionStorage.removeItem(key);
      localStorage.removeItem(key);
    } catch {
      /* приватный режим — просто пропускаем */
    }
  });
};

