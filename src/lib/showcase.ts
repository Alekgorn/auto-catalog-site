import { ShowcaseKit } from '@/lib/site-settings';
import { buildShareUrl } from '@/lib/share-kit';

/**
 * Ссылка на комплект витрины.
 *
 * Живёт отдельно от редактора: её зовут и из карточек витрины, и из
 * панели заявок. Пока функция лежала внутри компонента, один экран
 * админки тащил за собой другой целиком.
 *
 * Адрес собираем при сохранении, а не храним заведённым руками: формат
 * ссылки задан кодом, и при его изменении все карточки должны обновиться
 * сами, без ручной правки каждой.
 */
export const showcaseHref = (kit: ShowcaseKit): string =>
  buildShareUrl({
    lines: kit.ids.map((id) => ({ id, qty: 1 })),
    vehicle: null,
  });
