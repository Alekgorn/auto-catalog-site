/**
 * Сценарии использования — то, с чем покупатель приходит на сайт.
 *
 * Здесь и плитки на главной, и тексты страницы сценария. Всё в одном месте,
 * чтобы менять формулировки без правки вёрстки.
 */
export interface Scenario {
  /** Адрес страницы: /search?s=slug */
  slug: string;
  icon: string;
  /** Заголовок плитки — фраза покупателя */
  title: string;
  /** Короткая подпись на плитке */
  text: string;
  /** Запрос, который уходит в умный поиск */
  query: string;
  /** Заголовок страницы сценария */
  heading: string;
  /** Живой вводный текст на странице */
  intro: string;
  /** Что входит в решение — по шагам */
  steps: { title: string; text: string }[];
  /** Подсказка внизу страницы */
  hint?: string;
  /** Частые вопросы по теме сценария */
  faq: { q: string; a: string }[];
  /** Показывать весь каталог целиком, а не выборку по запросу */
  fullCatalog?: boolean;
  /** Брать товары только из этих разделов, минуя умный поиск */
  onlyCategories?: string[];
  /**
   * Скрыть подбор по машине: оборудование универсальное,
   * фильтровать нечего.
   */
  noVehicle?: boolean;
  /**
   * Пошаговая сборка комплекта: покупатель выбирает по одной позиции
   * из каждого блока и получает итоговую цену.
   */
  kit?: KitStep[];
}

/** Шаг сборки комплекта — один раздел каталога */
export interface KitStep {
  /** Раздел каталога, откуда берём товары */
  category: string;
  /** Заголовок блока */
  title: string;
  /** Пояснение под заголовком */
  text: string;
  icon: string;
  /** Показывать только товары дешевле этой цены */
  maxPrice?: number;
  /**
   * Показывать только товары дороже этой цены — премиум-подборка.
   * Что дешевле, открывается кнопкой «Показать дешевле».
   */
  minPrice?: number;
  /**
   * Шаг необязательный: его можно пропустить и идти дальше.
   * Комплект считается собранным и без него.
   */
  optional?: boolean;
  /** Список бессмысленен без выбранной машины — просим указать авто */
  needVehicle?: boolean;
  /** Название позиции для кнопки: «Заменить магнитолу» */
  unit?: string;
  /**
   * Показывать только товары, у которых машина указана в совместимости.
   * Универсальные позиции скрываем: для рамок и проводки «подойдёт почти
   * всем» означает, что покупатель возьмёт не то.
   */
  strictFit?: boolean;
  /**
   * Показывать большую кнопку «Не уверен, нужна помощь».
   * Нужна там, где покупателю сложно выбрать сам — например, разъёмы.
   */
  helpOffer?: boolean;
}

