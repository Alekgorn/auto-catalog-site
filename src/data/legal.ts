/**
 * Тексты юридических документов магазина.
 *
 * Держим их данными, а не вёрсткой: обе страницы рисует один компонент,
 * а реквизиты и контакты подставляются из настроек — поменяли телефон
 * в одном месте, и он поменялся в оферте.
 *
 * Документы описывают то, как магазин работает на самом деле: доставку
 * из delivery.ts, возврат за 14 дней и гарантию из FAQ. Расхождение
 * между текстом оферты и реальными условиями хуже, чем её отсутствие.
 */

export interface LegalSection {
  title: string;
  /** Абзацы раздела. Пункты списка начинаются с «— » */
  body: string[];
}

export interface LegalDoc {
  slug: string;
  /** Заголовок на странице и в поиске */
  title: string;
  /** Короткое пояснение под заголовком */
  note: string;
  /** Дата последнего изменения — обязательный реквизит документа */
  updated: string;
  sections: LegalSection[];
}

